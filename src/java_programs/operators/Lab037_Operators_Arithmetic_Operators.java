package java_programs.operators;

public class Lab037_Operators_Arithmetic_Operators {
    public static void main(String[] args) {
        // Arithmetic Operators
        //        + (Addition)
        //       - (Subtraction)
        //       * (Multiplication)
        //       / (Division)
        //       % (Modulus) | Modulus - Remainder

        int a = 20;
        int b = 3;
        System.out.println(a + b); // 23
        System.out.println(a - b); // 17
        System.out.println(a * b); // 60
        System.out.println(a / b); //6
        float c = 3.0f;
        System.out.println(a / c); // 6.66666665  //type casting
        System.out.println("a+b"); // a+b
            }
}
