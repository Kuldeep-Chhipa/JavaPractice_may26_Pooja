package java_programs.ex_04_Operators;

public class Lab036_Operators_Assignment  {
    public static void main(String[] args) {
        // assignment operators are used to assign values to variables in java
        // there are different types of assignment operators in java such as =, +=, -=, *=, /=, %= etc.

        int a = 10; // a is assigned the value 10 using the assignment operator =
     
     
        a += 5; // a is assigned the value of a + 5 using the assignment operator +=
        System.out.println("The value of a is: " + a); // printing the value of variable a = 15

        int b = 20; // b is assigned the value 20 using the assignment operator =
        b -= 5; // b is assigned the value of b - 5 using the assignment operator -=
        System.out.println("The value of b is: " + b); // printing the value of variable b = 15

        int c = 30; // c is assigned the value 30 using the assignment operator =
        c *= 2; // c is assigned the value of c * 2 using the assignment operator *=
        System.out.println("The value of c is: " + c); // printing the value of variable c = 60

        int d = 40; // d is assigned the value 40 using the assignment operator =
        d /= 4; // d is assigned the value of d / 4 using the assignment operator /=
        System.out.println("The value of d is: " + d); // printing the value of variable d = 10

        int e = 50; // e is assigned the value 50 using the assignment operator =
        e %= 3; // e is assigned the value of e % 3 using the assignment operator %=
        System.out.println("The value of e is: " + e); // printing the value of variable e = 2
    }
    
}
