package java_programs.ex_04_Operators;

public class Lab037_Operators_Arithmetic_Operators {
    public static void main(String[] args) {
        // arithmetic operators are used to perform arithmetic operations in java
        // there are different types of arithmetic operators in java such as +, -, *, /, % etc.

        int a = 10; // a is assigned the value 10
        int b = 20; // b is assigned the value 20

        int sum = a + b; // sum is assigned the value of a + b using the arithmetic operator +
        System.out.println("The sum of " + a + " and " + b + " is: " + sum); // printing the value of sum = 30

        int difference = a - b; // difference is assigned the value of a - b using the arithmetic operator -
        System.out.println("The difference of " + a + " and " + b + " is: " + difference); // printing the value of difference = -10

        int product = a * b; // product is assigned the value of a * b using the arithmetic operator *
        System.out.println("The product of " + a + " and " + b + " is: " + product); // printing the value of product = 200

        int quotient = a / b; // quotient is assigned the value of a / b using the arithmetic operator /
        System.out.println("The quotient of " + a + " and " + b + " is: " + quotient); // printing the value of quotient = 0

        int remainder = a % b; // remainder is assigned the value of a % b using the arithmetic operator %
        System.out.println("The remainder of " + a + " and " + b + " is: " + remainder); // printing the value of remainder = 10
    }
    
}
